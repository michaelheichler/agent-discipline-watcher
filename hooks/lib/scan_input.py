LEGACY_ENV_NAMES = {
    "ADW_FUNC_BLOCK_LINES": "CLEANCODER_FUNC_BLOCK_LINES",
}
FILE_LENGTH_WARNING = 500
FILE_LENGTH_CRITICAL = 750
FILE_LENGTH_BLOCK = 1000
SINK_DEVICES = frozenset({"/dev/null", "/dev/stdout", "/dev/stderr", "/dev/tty"})
FD_DEVICE_RE = re.compile(r"/dev/fd/\d+")
LOCKFILE_NAMES = frozenset({
    "uv.lock", "pnpm-lock.yaml", "package-lock.json", "npm-shrinkwrap.json", "yarn.lock", "poetry.lock",
    "Pipfile.lock", "Cargo.lock", "Gemfile.lock", "composer.lock", "go.sum", "bun.lock", "flake.lock",
    "mix.lock", "Podfile.lock", "pubspec.lock",
})
GENERATED_MARKER_RE = re.compile(r"@generated\b|\bDO NOT EDIT\b|\bauto-?generated\b|\bCode generated by\b", re.IGNORECASE)
GENERATED_HEAD_LINES = 5


def is_data_file(path: str | Path) -> bool:
    """Judged by name, because a split or a rewrite of data or a lockfile is not the agent's to make."""
    name = Path(path).name
    lowered = name.lower()
    return Path(lowered).suffix in DATA_TEXT_EXTS or name in LOCKFILE_NAMES or ".min." in lowered


def has_generated_marker(head: str) -> bool:
    return any(GENERATED_MARKER_RE.search(line) for line in head.splitlines()[:GENERATED_HEAD_LINES])


def _decodes(decoder: codecs.IncrementalDecoder, block: bytes, final: bool = False) -> bool:
    try:
        decoder.decode(block, final)
    except UnicodeDecodeError:
        return False
    return True


def _valid_utf8(handle: BinaryIO) -> bool:
    decoder = codecs.getincrementaldecoder("utf-8")()
    for block in iter(lambda: handle.read(1 << 16), b""):
        if b"\0" in block or not _decodes(decoder, block):
            return False
    return _decodes(decoder, b"", True)


def is_data_text(path: Path, handle: BinaryIO) -> bool:
    """Exempt from the size and length guards only as clean UTF-8, so a binary blob under a data name still blocks."""
    if not is_data_file(path):
        return False
    handle.seek(0)
    valid = _valid_utf8(handle)
    handle.seek(0)
    return valid


def file_length_policy(count: int) -> tuple[str, str] | None:
    if count >= FILE_LENGTH_BLOCK:
        return "file_too_long", "Split this file into focused modules."
    if count >= FILE_LENGTH_CRITICAL:
        return "file_length_critical", "Split this file now. It will hard block at 1000 lines."
    if count >= FILE_LENGTH_WARNING:
        return "file_length_warning", "Plan a focused split before this file reaches 750 lines."
    return None


def _count_open_file_lines(handle: BinaryIO) -> tuple[int, bool] | None:
    count = 0
    for line in handle:
        if b"\0" in line:
            return None
        count += 1
        if count >= FILE_LENGTH_BLOCK:
            return count, True
    return count, False


def file_line_count(path: Path) -> tuple[int, bool] | None:
    try:
        with open_regular(path) as handle:
            if is_binary_content(path, handle.read(CONTENT_SAMPLE_BYTES)):
                return None
            handle.seek(0)
            return _count_open_file_lines(handle)
    except OSError:
        return None


def fallback_findings_from_count(path: Path, count: int, capped: bool = True) -> list[dict]:
    policy = file_length_policy(count)
    if policy is not None and policy[0] == "file_too_long":
        rule, action = policy
        shown = f"at least {count}" if capped else str(count)
        detail = f"File has {shown} lines in {path}"
    else:
        rule = "unscannable_file"
        action = "Make the file readable UTF-8 text within the scan byte limit."
        detail = f"File could not be fully scanned: {path}"
    return [Finding(
        family="code",
        rule=rule,
        line=1,
        detail=detail,
        force=True,
        snippet=str(path)[:180],
        action=action,
        path=None,
        severity=None,
        tool_use_id=None,
    ).to_dict()]


def sink_device(raw_path: str) -> bool:
    """Because a sink device keeps no text, writing to it leaves no content a scan could owe."""
    text = raw_path.strip()
    return text in SINK_DEVICES or FD_DEVICE_RE.fullmatch(text) is not None


def nothing_landed(raw_path: str, cwd: Path) -> bool:
    """Because a missing file holds no text, a shell target that is gone after the run leaves no content a scan could owe."""
    text = raw_path.strip()
    if sink_device(text):
        return True
    # Because an unexpanded name may stand for a file that landed elsewhere.
    if "$" in text or "`" in text:
        return False
    try:
        candidate = Path(text).expanduser()
        os.lstat(candidate if candidate.is_absolute() else cwd / candidate)
    except (FileNotFoundError, NotADirectoryError):
        return True
    except (OSError, ValueError):
        return False
    return False


def fallback_findings(path: Path) -> list[dict]:
    try:
        with path.open("rb") as handle:
            if is_binary_content(path, handle.read(CONTENT_SAMPLE_BYTES)) or is_data_text(path, handle):
                return []
            handle.seek(0)
            result = _count_open_file_lines(handle)
    except OSError:
        result = None
    if result is None:
        return fallback_findings_from_count(path, 0, capped=False)
    count, capped = result
    return fallback_findings_from_count(path, count, capped)


def read_scannable(path: Path, config: dict) -> str | None:
    cfg = effective_config(config)
    try:
        if path.stat().st_size > _max_scan_bytes(cfg):
            return None
        raw = path.read_bytes()
    except OSError:
        return None
    if is_binary_content(path, raw) or b"\0" in raw[:CONTENT_SAMPLE_BYTES]:
        return None
    return raw.decode("utf-8", errors="replace")


def scannable_text(text: str, config: dict) -> str | None:
    if len(text) > _max_scan_bytes(effective_config(config)):
        return None
    if "\0" in text[:CONTENT_SAMPLE_BYTES]:
        return None
    return text


def _max_scan_bytes(config: dict) -> int:
    return int_setting(config, "max_scan_bytes", "ADW_MAX_SCAN_BYTES", 1_000_000)


def _env_setting(env_name: str, default: int) -> object:
    for name in (env_name, LEGACY_ENV_NAMES.get(env_name)):
        if name and name in os.environ:
            return os.environ[name]
    return default


def int_setting(config: dict, key: str, env_name: str, default: int) -> int:
    raw = config.get(key, _env_setting(env_name, default))
    try:
        return int(raw)
    except (TypeError, ValueError):
        return default
