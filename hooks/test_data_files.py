from __future__ import annotations

import json
from pathlib import Path

import pytest

import stop
from lib import baseline, blocker_state, scanner
from testing import make_repo, run_git

LONG_LINES = 1200


def _config(root: Path, **extra: object) -> dict:
    return {"ledger_root": str(root / "ledger"), "state_root": str(root / "state"), **extra}


def _stop_on(tmp_path: Path, target: Path, **extra: object) -> dict:
    config = _config(tmp_path, **extra)
    blocker_state.touch_paths("s1", "", [str(target)], config["state_root"])
    return stop.run({"session_id": "s1", "cwd": str(tmp_path), "hook_event_name": "Stop"}, config)


def _rules(path: Path, text: str) -> set[str]:
    return {row["rule"] for row in scanner.scan_all(str(path), text, {})}


@pytest.mark.parametrize("name", ["data.csv", "rows.tsv", "schema.sql", "app.min.js", "uv.lock", "Cargo.lock"])
def test_a_long_data_file_has_no_length_finding(tmp_path: Path, name: str) -> None:
    text = "a,b\n" * LONG_LINES

    assert "file_too_long" not in _rules(tmp_path / name, text)


def test_a_long_code_file_still_has_a_length_finding(tmp_path: Path) -> None:
    assert "file_too_long" in _rules(tmp_path / "module.py", "x = 1\n" * LONG_LINES)


def test_an_oversized_json_is_not_an_unscannable_blocker(tmp_path: Path) -> None:
    target = tmp_path / "font-index.json"
    target.write_text(json.dumps({"glyphs": ["a" * 64] * 20}), encoding="utf-8")

    assert _stop_on(tmp_path, target, max_scan_bytes=100) == {}


def test_an_oversized_py_still_blocks_as_unscannable_or_too_long(tmp_path: Path) -> None:
    target = tmp_path / "big.py"
    target.write_text("x = 1\n" * 50, encoding="utf-8")

    response = _stop_on(tmp_path, target, max_scan_bytes=100)

    assert response["decision"] == "block"
    assert "unscannable_file" in response["reason"]


def test_a_binary_blob_named_like_data_still_blocks(tmp_path: Path) -> None:
    target = tmp_path / "blob.json"
    target.write_bytes(b"\xff\xfe\x00\x01" * 100)

    response = _stop_on(tmp_path, target, max_scan_bytes=100)

    assert response["decision"] == "block"


def _committed(tmp_path: Path, name: str, body: str) -> Path:
    tmp_path.mkdir(parents=True, exist_ok=True)
    repo = make_repo(tmp_path)
    target = repo / name
    target.write_text(body, encoding="utf-8")
    run_git(repo, "add", name)
    run_git(repo, "commit", "-qm", "seed")
    return target


def _length_split(target: Path, text: str) -> tuple[list[str], list[str]]:
    findings = scanner.scan_all(str(target), text, {})
    owned, inherited = baseline.split_committed(target, findings, {"baseline": "report"}, text)
    return [row["rule"] for row in owned], [row["rule"] for row in inherited]


def test_an_edit_that_keeps_an_inherited_long_file_as_long_does_not_own_its_length(tmp_path: Path) -> None:
    target = _committed(tmp_path, "module.py", "".join(f"value_{n} = {n}\n" for n in range(LONG_LINES)))
    edited = target.read_text(encoding="utf-8").replace("value_5 = 5", "value_5 = 6")

    owned, inherited = _length_split(target, edited)

    assert "file_too_long" not in owned
    assert "file_too_long" in inherited


def test_an_edit_that_grows_an_inherited_long_file_owns_its_length(tmp_path: Path) -> None:
    target = _committed(tmp_path, "module.py", "".join(f"value_{n} = {n}\n" for n in range(LONG_LINES)))

    owned, _inherited = _length_split(target, target.read_text(encoding="utf-8") + "extra = 1\n")

    assert "file_too_long" in owned


def test_a_generated_marker_relieves_growth_only_when_the_baseline_had_it(tmp_path: Path) -> None:
    body = "".join(f"value_{n} = {n}\n" for n in range(LONG_LINES))
    generated = _committed(tmp_path / "a", "gen.py", "# Code generated by protoc. DO NOT EDIT.\n" + body)
    plain = _committed(tmp_path / "b", "plain.py", body)

    grown_generated = _length_split(generated, generated.read_text(encoding="utf-8") + "extra = 1\n")
    marked_plain = _length_split(plain, "# DO NOT EDIT.\n" + body + "extra = 1\n")

    assert "file_too_long" not in grown_generated[0]
    assert "file_too_long" in marked_plain[0]
